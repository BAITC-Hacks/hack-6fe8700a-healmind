def build_analysis_prompt(result):
    """
    Формирует промпт для AI на основе
    готовых результатов симулятора.
    """

    prompt = f"""
Ты — AI-аналитик городского планирования Астаны.

Все математические расчёты уже выполнены симулятором.
Не изменяй и не придумывай числа.

Результаты симуляции:
{result}

Кратко объясни:

1. Почему изменился Astana Quality of Life Score.
2. Какие районы получили наибольшую пользу.
3. Какие показатели улучшились.
4. Какие критические проблемы остались.
5. Какие компромиссы есть у выбранных решений.

Используй только предоставленные данные.
Не рассчитывай Score самостоятельно.
"""

    return prompt