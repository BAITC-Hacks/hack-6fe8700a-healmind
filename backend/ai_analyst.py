from openai import OpenAI

client = OpenAI()


def analyze_result(result):
    prompt = f"""
Ты — AI-аналитик городского планирования Астаны.

Перед тобой результат математического симулятора городского бюджета.

ВАЖНО:
- Не рассчитывай Score самостоятельно.
- Не изменяй числа.
- Не придумывай отсутствующие данные.
- Используй только результат симулятора.

Результат:
{result}

Дай краткий анализ на русском языке:

1. Почему изменился Astana Quality of Life Score?
2. Какие районы получили наибольшую пользу?
3. Какие показатели улучшились сильнее всего?
4. Какие критические показатели ниже 40 остались?
5. Какие компромиссы есть у выбранных решений?

Ответ должен быть понятен обычному жителю города.
"""

    response = client.responses.create(
        model="gpt-5.6-luna",
        input=prompt
    )

    return response.output_text 